# Keeps the discourse-fomio-app-locales plugin's site texts in step with the app (manifest source schema 3).
#
#   ruby Localization/tools/site-texts.rb sync  <plugin dir>   # refresh derived manifest fields, write plugin files
#   ruby Localization/tools/site-texts.rb check <plugin dir>   # exit 1 when sync would change anything
#
# Sources (this repository): Fomio/Resources/Localization/fomio-catalog-en.json (bundled English),
# Localization/manifest.json and Localization/catalogs/<locale>.json (reviewed translations of Fomio keys).
# Plugin output: catalogs/manifest.json and catalogs/en.json (copies) and config/locales/fomio_app.<locale>.yml,
# which holds every Fomio key as a Discourse translation key (`fomio_app.<key, "." written "__">`, flat because
# some keys are prefixes of others) with {name} written %{name}, so an administrator can override it in
# Admin > Customize > Text. Mapped keys keep their Discourse key and are not written. Derived manifest fields:
# `schema`, each Fomio entry's `site_text_key`, and `terminology.keys` (keys whose English contains a noun).
require "json"
require "yaml"

ROOT = File.expand_path("../..", __dir__)
ENGLISH = File.join(ROOT, "Fomio/Resources/Localization/fomio-catalog-en.json")
MANIFEST = File.join(ROOT, "Localization/manifest.json")
TRANSLATIONS = File.join(ROOT, "Localization/catalogs")
NAMESPACE = "fomio_app"
SOURCE_SCHEMA = 3
NOUNS = { "discussion" => /discussion/i, "community" => /communit(?:y|ies)/i }.freeze
HEADER = <<~YAML
  # Generated by the Fomio app repository's Localization/tools/site-texts.rb; do not edit here.
  # Administrators override these in Admin > Customize > Text; the catalog builder validates every value.
YAML

def read_json(path) = JSON.parse(File.read(path, encoding: "UTF-8"))

# Matches the existing files: one-space indentation, UTF-8 kept, trailing newline.
def format_json(object) = JSON.pretty_generate(object, indent: " ") + "\n"

def site_text_key(key) = "#{NAMESPACE}.#{key.gsub(".", "__")}"

def to_discourse(value)
  convert = ->(text) { text.gsub(/\{([a-z][A-Za-z0-9_]*)\}/, '%{\1}') }
  value.is_a?(Hash) ? value.transform_values(&convert) : convert.(value)
end

def plain(value) = value.is_a?(Hash) ? value.values.join(" ") : value

def yaml_file(locale, messages)
  data = { locale => { NAMESPACE => messages.sort.to_h } }
  text = HEADER + YAML.dump(data, line_width: -1).delete_prefix("---\n")
  abort("#{locale}: YAML does not round-trip") unless YAML.safe_load(text) == data
  text
end

def outputs(plugin)
  manifest = read_json(MANIFEST)
  english = read_json(ENGLISH)["messages"]
  keys = manifest["keys"]
  abort("manifest and English keys differ") unless keys.keys.sort == english.keys.sort
  fomio = keys.select { |_, entry| entry["source"] == "fomio" }.keys

  manifest["schema"] = SOURCE_SCHEMA
  keys.each do |key, entry|
    entry["source"] == "fomio" ? entry["site_text_key"] = site_text_key(key) : entry.delete("site_text_key")
  end
  manifest["terminology"]["keys"] =
    NOUNS.to_h { |noun, pattern| [noun, english.select { |_, v| plain(v).match?(pattern) }.keys.sort] }

  site_texts = ->(messages) { messages.to_h { |key, value| [site_text_key(key).delete_prefix("#{NAMESPACE}."), to_discourse(value)] } }
  files = {
    MANIFEST => format_json(manifest),
    File.join(plugin, "catalogs/manifest.json") => format_json(manifest),
    File.join(plugin, "catalogs/en.json") => File.read(ENGLISH, encoding: "UTF-8"),
    File.join(plugin, "config/locales/fomio_app.en.yml") => yaml_file("en", site_texts.(english.slice(*fomio))),
  }
  Dir[File.join(TRANSLATIONS, "*.json")].sort.each do |path|
    catalog = read_json(path)
    locale = catalog["locale"]
    abort("#{path}: locale #{locale.inspect} does not match the file name") unless File.basename(path, ".json") == locale
    extra = catalog["messages"].keys - fomio
    abort("#{path}: only Fomio keys may be translated here: #{extra.first(5).join(", ")}") if extra.any?
    files[File.join(plugin, "config/locales/fomio_app.#{locale}.yml")] = yaml_file(locale, site_texts.(catalog["messages"]))
  end
  # Retired schema-2 overlays and site-text files of translations that no longer exist.
  stale =
    (Dir[File.join(plugin, "catalogs/*.json")] + Dir[File.join(plugin, "config/locales/fomio_app.*.yml")])
      .reject { |path| files.key?(path) }
  [files, stale]
end

mode, plugin = ARGV
abort("usage: site-texts.rb sync|check <plugin dir>") unless %w[sync check].include?(mode) && plugin && File.directory?(plugin)
plugin = File.expand_path(plugin)
files, stale = outputs(plugin)
changed = files.reject { |path, text| File.exist?(path) && File.read(path, encoding: "UTF-8") == text }

if mode == "check"
  problems = changed.keys.map { |path| "out of date: #{path}" } + stale.map { |path| "stale: #{path}" }
  puts(problems.empty? ? "site texts in sync (#{files.size} files)" : problems)
  exit(problems.empty? ? 0 : 1)
end

changed.each { |path, text| File.write(path, text) }
stale.each { |path| File.delete(path) }
puts "wrote #{changed.size} file(s), removed #{stale.size} (#{files.size} files in sync)"
